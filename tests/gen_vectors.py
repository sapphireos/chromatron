# Generates build/vectors.h from the hash test vectors at the repo root:
#
#   kv_hashes.json      "__KV__<name>" -> uint32 hash of <name>
#   catbus_hashes.json  uint32 hash    -> <name>
#
# usage: gen_vectors.py <repo_root> <out_header>

import json
import sys


def c_str(s):
    # names are expected to be [A-Za-z0-9_]; escape anything else
    if all(c.isalnum() or c == '_' for c in s):
        return s
    return ''.join(c if (c.isalnum() or c == '_') else '\\x%02x' % ord(c)
                   for c in s)


def main():
    repo, out = sys.argv[1], sys.argv[2]

    kv = json.load(open(repo + '/kv_hashes.json'))
    catbus = json.load(open(repo + '/catbus_hashes.json'))

    kv_rows = []
    for key, h in kv.items():
        name = key[len('__KV__'):] if key.startswith('__KV__') else key
        kv_rows.append('    {"%s", (uint32_t)0x%08x},' % (c_str(name), h))

    cb_rows = []
    for h, name in catbus.items():
        cb_rows.append('    {0x%08x, "%s"},' % (int(h), c_str(name)))

    with open(out, 'w') as f:
        f.write('// generated by gen_vectors.py - do not edit\n')
        f.write('#include <stdint.h>\n')
        f.write('\n')
        f.write('typedef struct { const char *name; uint32_t hash; } kv_vector_t;\n')
        f.write('static const kv_vector_t KV_VECTORS[] = {\n')
        f.write('\n'.join(kv_rows) + '\n')
        f.write('};\n')
        f.write('static const unsigned int KV_VECTORS_COUNT = %d;\n' % len(kv_rows))
        f.write('\n')
        f.write('typedef struct { uint32_t hash; const char *name; } catbus_vector_t;\n')
        f.write('static const catbus_vector_t CATBUS_VECTORS[] = {\n')
        f.write('\n'.join(cb_rows) + '\n')
        f.write('};\n')
        f.write('static const unsigned int CATBUS_VECTORS_COUNT = %d;\n' % len(cb_rows))

    print('vectors: %d kv, %d catbus -> %s' % (len(kv_rows), len(cb_rows), out))


if __name__ == '__main__':
    main()
